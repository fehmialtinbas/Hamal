local T = require("harness")
local F = require("fixtures")

T.describe("Commands.ExtractItem", function()
  T.it("reads classic-style item links", function()
    local _, ns = F.setup()
    local link = "|cffffffff|Hitem:2589::::::::24:::::::|h[Linen Cloth]|h|r"
    local id, rest = ns.Commands.ExtractItem("Vault Keeper " .. link)
    T.eq(id, 2589)
    T.eq(rest, "Vault Keeper")
  end)

  T.it("reads modern quality-colored item links", function()
    local _, ns = F.setup()
    local link = "|cnIQ2:|Hitem:1000::::::::24:::::::|h[Green Sword]|h|r"
    local id, rest = ns.Commands.ExtractItem(link .. " Vault Keeper")
    T.eq(id, 1000)
    T.eq(rest, "Vault Keeper")
  end)

  T.it("reads a bare item ID", function()
    local _, ns = F.setup()
    local id, rest = ns.Commands.ExtractItem("Vault Keeper 2589")
    T.eq(id, 2589)
    T.eq(rest, "Vault Keeper")
    T.eq((ns.Commands.ExtractItem("2589")), 2589)
    T.eq((ns.Commands.ExtractItem("Vault Keeper")), nil)
  end)
end)

T.describe("Slash commands", function()
  T.it("add an alt and toggle item types", function()
    local _, ns = F.setup()
    SlashCmdList.HAMAL("add Vault Keeper")
    SlashCmdList.HAMAL("cat vault cloth Herb")
    local mule = ns.db.mules["vault keeper"]
    T.truthy(mule, "mule added")
    T.truthy(mule.categories.cloth, "cloth on")
    T.truthy(mule.categories.herb, "herb on")
    SlashCmdList.HAMAL("cat Vault Keeper herb")
    T.eq(mule.categories.herb, nil, "herb toggled off")
  end)

  T.it("toggle single items, exclusions and aliases", function()
    local w, ns = F.setup()
    SlashCmdList.HAMAL("add Vault Keeper")
    SlashCmdList.HAMAL("item |cffffffff|Hitem:2447::::|h[Peacebloom]|h|r")
    T.truthy(ns.db.mules["vault keeper"].items[2447], "item rule without a name when there is one alt")
    SlashCmdList.HAMAL("exclude 2589")
    T.truthy(ns.db.exclude[2589], "excluded")
    SlashCmdList.HAMAL("alias vk vault")
    T.eq(ns.db.aliases.vk, "vault keeper")
    SlashCmdList.HAMAL("chain off")
    T.eq(ns.db.options.chain, false)
    SlashCmdList.HAMAL("nonsense")
    T.truthy(w:Printed("/hamal add"), "unknown command prints help")
  end)

  T.it("previews what would be sent", function()
    local w = F.withVault()
    w:Fill(2589, 14, 20)
    SlashCmdList.HAMAL("preview")
    T.truthy(w:Printed("14 stack%(s%) go to Vault Keeper in 2 mail"), "preview summary")
  end)
end)
