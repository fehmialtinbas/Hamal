local T = require("harness")
local F = require("fixtures")

local function openSettings(ns)
  SlashCmdList.HAMAL("")
  return ns.Config.widgets
end

local function categoryCheck(ui, key)
  for _, check in ipairs(ui.categoryChecks) do
    if check.category == key then return check end
  end
end

T.describe("Settings window", function()
  T.it("opens with /hamal and adds a bank alt", function()
    local w, ns = F.setup()
    local ui = openSettings(ns)
    T.truthy(ns.Config.frame:IsShown(), "window open")
    w:Enter(ui.nameBox, "Vault Keeper")
    T.truthy(ns.db.mules["vault keeper"], "added")
    T.eq(ui.header:GetText(), "Vault Keeper")
    T.eq(ui.muleButtons[1]:GetText(), "Vault Keeper")
    T.eq(ui.nameBox:GetText(), "")
  end)

  T.it("gives each bank alt its own item types", function()
    local w, ns = F.setup()
    ns.Mules.Add(ns.db, "Cloth Bank")
    ns.Mules.Add(ns.db, "Herb Bank")
    local ui = openSettings(ns)
    T.eq(ui.header:GetText(), "Cloth Bank", "first alt selected")
    local cloth, herb = categoryCheck(ui, "cloth"), categoryCheck(ui, "herb")
    w:Click(cloth)
    w:Click(ui.muleButtons[2])
    T.eq(ui.header:GetText(), "Herb Bank")
    T.eq(cloth:GetChecked(), false, "Herb Bank has no cloth")
    T.truthy(cloth.label:GetText():find("Cloth Bank"), "label says who gets cloth")
    w:Click(herb)
    T.truthy(ns.db.mules["cloth bank"].categories.cloth, "cloth rule")
    T.truthy(ns.db.mules["herb bank"].categories.herb, "herb rule")
    T.eq(ns.db.mules["herb bank"].categories.cloth, nil)

    w:Put(0, 1, F.LINEN, 20)
    w:Put(0, 2, F.PEACEBLOOM, 5)
    w:Put(0, 3, F.LINEN, 20)
    local counts = ns.Scanner.CountAll(ns.db)
    T.eq(counts["cloth bank"], 2)
    T.eq(counts["herb bank"], 1)
  end)

  T.it("warns when two alts tick the same type", function()
    local w, ns = F.setup()
    local a = ns.Mules.Add(ns.db, "Alpha Bank")
    ns.Mules.Add(ns.db, "Zeta Bank")
    ns.Mules.ToggleCategory(ns.db, a, "cloth")
    local ui = openSettings(ns)
    w:Click(ui.muleButtons[2])
    local cloth = categoryCheck(ui, "cloth")
    w:Click(cloth)
    T.truthy(cloth.label:GetText():find("goes to Alpha Bank"), "warning on the label")
  end)

  T.it("adds single items by drag and drop and removes them by click", function()
    local w, ns = F.setup()
    ns.Mules.Add(ns.db, "Vault Keeper")
    w:Put(0, 1, F.PEACEBLOOM, 5)
    local ui = openSettings(ns)
    w:DragItem(0, 1, ui.itemDrop)
    T.truthy(ns.db.mules["vault keeper"].items[F.PEACEBLOOM], "item rule")
    T.eq(w.cursor, nil, "item went back to the bag")
    T.eq(w:LockedInBags(), 0)
    T.truthy(ui.itemButtons[1]:IsShown(), "icon shown")
    T.eq(ui.itemButtons[1].itemID, F.PEACEBLOOM)
    w:Click(ui.itemButtons[1])
    T.eq(ns.db.mules["vault keeper"].items[F.PEACEBLOOM], nil, "removed")
    T.truthy(not ui.itemButtons[1]:IsShown(), "icon hidden")
  end)

  T.it("keeps never-send items out of every alt", function()
    local w, ns = F.setup()
    local key = ns.Mules.Add(ns.db, "Vault Keeper")
    ns.Mules.ToggleItem(ns.db, key, F.LINEN)
    w:Put(0, 1, F.LINEN, 20)
    local ui = openSettings(ns)
    w:DragItem(0, 1, ui.excludeDrop)
    T.truthy(ns.db.exclude[F.LINEN], "excluded")
    T.eq(ns.db.mules[key].items[F.LINEN], nil, "item rule dropped")
    T.eq(ui.excludeButtons[1].itemID, F.LINEN)
    w:Click(ui.excludeButtons[1])
    T.eq(ns.db.exclude[F.LINEN], nil, "back off the list")
  end)

  T.it("keeps one shortcut per bank alt", function()
    local w, ns = F.setup()
    local key = ns.Mules.Add(ns.db, "Vault Keeper")
    local ui = openSettings(ns)
    w:Enter(ui.aliasBox, "vk")
    T.eq(ns.db.aliases.vk, key)
    w:Enter(ui.aliasBox, "vv")
    T.eq(ns.db.aliases.vk, nil, "old shortcut gone")
    T.eq(ns.db.aliases.vv, key)
    w:Enter(ui.aliasBox, "")
    T.eq(ns.db.aliases.vv, nil, "cleared")
  end)

  T.it("asks before removing a bank alt", function()
    local w, ns = F.setup()
    ns.Mules.Add(ns.db, "Vault Keeper")
    ns.Mules.Add(ns.db, "Herb Bank")
    local ui = openSettings(ns)
    T.eq(ui.header:GetText(), "Herb Bank")
    w:Click(ui.removeButton)
    T.truthy(ns.db.mules["herb bank"], "not removed before confirming")
    w:AcceptPopup()
    T.eq(ns.db.mules["herb bank"], nil, "removed")
    T.eq(ui.header:GetText(), "Vault Keeper", "next alt selected")
  end)

  T.it("switches the options", function()
    local w, ns = F.setup()
    local ui = openSettings(ns)
    T.eq(ui.autoCheck:GetChecked(), true)
    w:Click(ui.autoCheck)
    w:Click(ui.chainCheck)
    T.eq(ns.db.options.autoAttach, false)
    T.eq(ns.db.options.chain, false)
  end)

  T.it("opens from the mailbox panel on the bank alt being filled", function()
    local w, ns = F.setup()
    local cloth = ns.Mules.Add(ns.db, "Cloth Bank")
    local herb = ns.Mules.Add(ns.db, "Herb Bank")
    ns.Mules.ToggleCategory(ns.db, cloth, "cloth")
    ns.Mules.ToggleCategory(ns.db, herb, "herb")
    w:Fill(F.PEACEBLOOM, 2, 5)
    w:OpenMailbox()
    w:Click(ns.UI.muleButtons[2])
    T.eq(ns.Mailer.session.key, herb)
    w:Click(ns.UI.settingsButton)
    T.truthy(ns.Config.frame:IsShown(), "window open")
    T.eq(ns.Config.widgets.header:GetText(), "Herb Bank")
  end)
end)
