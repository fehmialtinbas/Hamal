local T = require("harness")
local F = require("fixtures")

T.describe("Robustness", function()
  T.it("keeps other handlers running when one fails", function()
    local w, ns = F.setup(function(w) w.useErrorHandler = true end)
    local ran = false
    ns.On("BAG_UPDATE_DELAYED", function() error("boom") end)
    ns.On("BAG_UPDATE_DELAYED", function() ran = true end)
    w:Fire("BAG_UPDATE_DELAYED")
    T.truthy(ran, "the next handler still ran")
    T.eq(#w.errors, 1, "the error went to the game's error frame")
  end)

  T.it("notices the mailbox through either event, once per visit", function()
    local w, ns = F.withVault()
    ns.db.options.autoSendOnOpen = true
    w:Fill(F.LINEN, 5, 20)
    MailFrame:Show()
    SendMailFrame.shown = true
    w:Fire("PLAYER_INTERACTION_MANAGER_FRAME_SHOW", 17)
    w:Fire("MAIL_SHOW")
    w:Flush()
    T.truthy(ns.UI.panel, "panel built")
    T.eq(#w.sent, 1, "sent once, not twice")
    w:Fire("PLAYER_INTERACTION_MANAGER_FRAME_HIDE", 17)
    w:Fill(F.LINEN, 2, 20)
    w:Fire("PLAYER_INTERACTION_MANAGER_FRAME_SHOW", 17)
    w:Flush()
    T.eq(#w.sent, 2, "the next visit is handled again")
  end)

  T.it("ignores other interactions such as a vendor", function()
    local w, ns = F.withVault()
    ns.db.options.autoSendOnOpen = true
    w:Fill(F.LINEN, 5, 20)
    w:Fire("PLAYER_INTERACTION_MANAGER_FRAME_SHOW", 5)
    w:Flush()
    T.eq(ns.UI.panel, nil)
    T.eq(#w.sent, 0)
  end)

  T.it("doesn't offer a bank alt to itself in the mailbox panel", function()
    local w, ns = F.setup()
    local me = F.addMule(ns, "Main Character")
    ns.Mules.ToggleCategory(ns.db, me, "cloth")
    w:Fill(F.LINEN, 2, 20)
    w:OpenMailbox()
    local first = ns.UI.muleButtons[1]
    T.truthy(not first or not first:IsShown(), "no button for itself")
    T.truthy(ns.UI.status:GetText():find("is a bank alt"), "says so instead")
    T.truthy(not ns.UI.sendAllButton:IsShown(), "nothing to send")
  end)

  T.it("reports what it sees with /hamal status", function()
    local w = F.withVault()
    w:Fill(F.LINEN, 2, 20)
    SlashCmdList.HAMAL("status")
    T.truthy(w:Printed("version dev"), "version")
    T.truthy(w:Printed("you: Main Character | realm: PvP | ruleset: PvP"), "character line")
    T.truthy(w:Printed("bank alt Vault Keeper: here, can be mailed, 2 stack"), "bank alt line")
    T.truthy(w:Printed("class 7 / subclass 5"), "item class line")
  end)
end)
