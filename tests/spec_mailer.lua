local T = require("harness")
local F = require("fixtures")

local function sentCounts(w)
  local counts = {}
  for i, mail in ipairs(w.sent) do counts[i] = #mail.items end
  return table.concat(counts, ",")
end

T.describe("Mailer", function()
  T.it("sends everything in batches of 12 with one click", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 27, 20)
    w:Fill(F.PEACEBLOOM, 3, 5)
    w:OpenMailbox()
    T.eq(ns.UI.muleButtons[1]:GetText(), "Vault Keeper (27)")
    w:Click(ns.UI.muleButtons[1])
    T.eq(SendMailNameEditBox:GetText(), "Vault Keeper")
    T.eq(ns.Mailer.AttachedCount(), 12)
    T.eq(ns.UI.sendButton:GetText(), "Send mail 1/3")
    w:Click(ns.UI.sendButton)
    w:Flush()
    T.eq(sentCounts(w), "12,12,3")
    for _, mail in ipairs(w.sent) do
      T.eq(mail.to, "Vault Keeper")
    end
    T.eq(w.sent[1].subject, "Hamal 1/3")
    T.eq(w:StacksInBags(F.LINEN), 0)
    T.eq(w:StacksInBags(F.PEACEBLOOM), 3, "herbs stay")
    T.eq(ns.Mailer.session, nil)
    T.truthy(w:Printed("Sent 27 stack%(s%) to Vault Keeper in 3 mail"), "summary")
  end)

  T.it("falls back to one click per mail when the game blocks chained sends", function()
    local w, ns = F.withVault()
    w.requireHardware = true
    w:Fill(F.LINEN, 27, 20)
    w:OpenMailbox()
    w:Click(ns.UI.muleButtons[1])
    w:Click(ns.UI.sendButton)
    w:Flush()
    T.eq(sentCounts(w), "12", "first mail went out, the chained one was blocked")
    T.eq(ns.db.options.chain, false, "chaining switched off")
    T.eq(ns.Mailer.AttachedCount(), 12, "next batch waits in the form")
    T.truthy(ns.UI.sendButton:IsEnabled(), "send button ready")
    w:Click(ns.UI.sendButton)
    w:Flush()
    T.eq(sentCounts(w), "12,12")
    w:Click(ns.UI.sendButton)
    w:Flush()
    T.eq(sentCounts(w), "12,12,3")
    T.eq(ns.Mailer.session, nil)
  end)

  T.it("fills the mail when a bank alt's name is typed, without sending", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 5, 20)
    w:OpenMailbox()
    w:Type("vault keeper")
    w:Flush()
    T.eq(ns.Mailer.AttachedCount(), 5)
    T.eq(SendMailNameEditBox:GetText(), "Vault Keeper")
    T.eq(#w.sent, 0)
  end)

  T.it("expands an alias typed in To:", function()
    local w, ns, key = F.withVault()
    ns.Mules.SetAlias(ns.db, "vk", key)
    w:Fill(F.LINEN, 2, 20)
    w:OpenMailbox()
    w:Type("vk")
    w:Flush()
    T.eq(SendMailNameEditBox:GetText(), "Vault Keeper")
    T.eq(ns.Mailer.AttachedCount(), 2)
  end)

  T.it("does nothing on a partial name or with auto-fill off", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 2, 20)
    w:OpenMailbox()
    w:Type("vault")
    w:Flush()
    T.eq(ns.Mailer.AttachedCount(), 0, "partial name")
    ns.db.options.autoAttach = false
    w:Type("vault keeper")
    w:Flush()
    T.eq(ns.Mailer.AttachedCount(), 0, "auto-fill off")
  end)

  T.it("takes the items back out when the player writes to someone else", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 5, 20)
    w:OpenMailbox()
    w:Type("vault keeper")
    w:Flush()
    T.eq(ns.Mailer.AttachedCount(), 5)
    w:Type("Some Friend")
    w:Flush()
    T.eq(ns.Mailer.AttachedCount(), 0)
    T.eq(ns.Mailer.session, nil)
    T.eq(w:LockedInBags(), 0, "items are free again")
  end)

  T.it("keeps going when the default Send button is used", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 15, 20)
    w:OpenMailbox()
    w:Type("Vault Keeper")
    w:Flush()
    w.hardware = true
    SendMail(SendMailNameEditBox:GetText(), "Linen Cloth", "")
    w.hardware = false
    w:Flush()
    T.eq(sentCounts(w), "12,3")
    T.eq(ns.Mailer.session, nil)
  end)

  T.it("keeps the batch after a failed mail so it can be retried", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 15, 20)
    w:OpenMailbox()
    w:Click(ns.UI.muleButtons[1])
    w.failNext = true
    w:Click(ns.UI.sendButton)
    w:Flush()
    T.eq(#w.sent, 0)
    T.truthy(w:Printed("failed"), "failure message")
    T.eq(ns.Mailer.AttachedCount(), 12)
    T.eq(ns.UI.sendButton:GetText(), "Send mail 1/2")
    w:Click(ns.UI.sendButton)
    w:Flush()
    T.eq(sentCounts(w), "12", "after a failure the player confirms each mail")
  end)

  T.it("will not send without enough money for postage", function()
    local w, ns = F.withVault()
    w.money = 100
    w:Fill(F.LINEN, 12, 20)
    w:OpenMailbox()
    w:Click(ns.UI.muleButtons[1])
    w:Click(ns.UI.sendButton)
    w:Flush()
    T.eq(#w.sent, 0)
    T.truthy(w:Printed("Not enough money"), "postage message")
  end)

  T.it("refuses to fill a bank alt from itself", function()
    local w, ns, key = F.withVault()
    w.playerName = "Vault Keeper"
    w:Fill(F.LINEN, 2, 20)
    w:OpenMailbox()
    T.eq(ns.Mailer.Start(key), false)
    T.truthy(w:Printed("You are logged in as Vault Keeper"), "message")
  end)

  T.it("leaves a stack out when its icon is clicked", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 15, 20)
    w:OpenMailbox()
    w:Type("Vault Keeper")
    w:Flush()
    T.eq(#ns.Mailer.SessionItems(), 15)
    local first = ns.UI.itemButtons[1]
    T.truthy(first:IsShown(), "icons shown")
    w:Click(first)
    T.eq(#ns.Mailer.SessionItems(), 14)
    T.eq(ns.Mailer.AttachedCount(), 12, "freed slot refilled from the queue")
    w:Click(ns.UI.sendButton)
    w:Flush()
    T.eq(sentCounts(w), "12,2")
    T.eq(w:StacksInBags(F.LINEN), 1, "the skipped stack stayed")
    T.eq(w:LockedInBags(), 0)
  end)

  T.it("never sends an item that is shift-clicked", function()
    local w, ns, key = F.withVault()
    ns.Mules.ToggleCategory(ns.db, key, "herb")
    w:Fill(F.LINEN, 3, 20)
    w:Fill(F.PEACEBLOOM, 2, 5)
    w:OpenMailbox()
    w:Type("Vault Keeper")
    w:Flush()
    T.eq(ns.UI.itemButtons[4].item.itemID, F.PEACEBLOOM, "cloth first, then herbs")
    w:ShiftClick(ns.UI.itemButtons[4])
    T.truthy(ns.db.exclude[F.PEACEBLOOM], "on the never-send list")
    T.eq(#ns.Mailer.SessionItems(), 3, "both herb stacks left out")
    T.eq(ns.Mailer.AttachedCount(), 3)
  end)

  T.it("ends quietly when every stack is left out", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 1, 20)
    w:OpenMailbox()
    w:Type("Vault Keeper")
    w:Flush()
    w:Click(ns.UI.itemButtons[1])
    T.eq(ns.Mailer.session, nil)
    T.eq(ns.Mailer.AttachedCount(), 0)
  end)

  T.it("sends to every bank alt with one click", function()
    local w, ns = F.setup()
    local cloth = ns.Mules.Add(ns.db, "Cloth Bank")
    local herb = ns.Mules.Add(ns.db, "Herb Bank")
    ns.Mules.ToggleCategory(ns.db, cloth, "cloth")
    ns.Mules.ToggleCategory(ns.db, herb, "herb")
    w:Fill(F.LINEN, 15, 20)
    w:Fill(F.PEACEBLOOM, 3, 5)
    w:OpenMailbox()
    T.eq(ns.UI.sendAllButton:GetText(), "Send all: 18 stack(s) to 2 alt(s)")
    w:Click(ns.UI.sendAllButton)
    w:Flush()
    T.eq(sentCounts(w), "12,3,3")
    T.eq(w.sent[1].to, "Cloth Bank")
    T.eq(w.sent[3].to, "Herb Bank")
    T.eq(w:StacksInBags(F.LINEN) + w:StacksInBags(F.PEACEBLOOM), 0)
    T.eq(ns.Mailer.run, nil)
    T.truthy(w:Printed("All bank alts are done"), "summary")
  end)

  T.it("sends to every bank alt when the mailbox opens, if asked to", function()
    local w, ns = F.setup()
    local cloth = ns.Mules.Add(ns.db, "Cloth Bank")
    ns.Mules.ToggleCategory(ns.db, cloth, "cloth")
    ns.db.options.autoSendOnOpen = true
    w:Fill(F.LINEN, 5, 20)
    w:OpenMailbox()
    w:Flush()
    T.eq(sentCounts(w), "5")
  end)

  T.it("leaves out disabled bank alts and this character", function()
    local w, ns = F.setup()
    local cloth = ns.Mules.Add(ns.db, "Cloth Bank")
    local me = ns.Mules.Add(ns.db, "Main Character")
    ns.Mules.ToggleCategory(ns.db, cloth, "cloth")
    ns.Mules.ToggleCategory(ns.db, me, "herb")
    w:Fill(F.LINEN, 2, 20)
    w:Fill(F.PEACEBLOOM, 2, 5)
    ns.db.mules[cloth].disabled = true
    w:OpenMailbox()
    T.eq(#ns.Mailer.PendingAlts(), 0)
    T.truthy(not ns.UI.sendAllButton:IsShown(), "no send-all button")
  end)

  T.it("ends the session when the mailbox closes", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 20, 20)
    w:OpenMailbox()
    w:Click(ns.UI.muleButtons[1])
    w:CloseMailbox()
    T.eq(ns.Mailer.session, nil)
    T.truthy(w:Printed("Mailbox closed"), "message")
  end)
end)
