local T = require("harness")
local F = require("fixtures")

T.describe("Categories", function()
  T.it("match on item class and subclass", function()
    local _, ns = F.setup()
    local C = ns.Categories
    T.truthy(C.Matches("cloth", { classID = 7, subclassID = 5 }), "cloth")
    T.truthy(not C.Matches("cloth", { classID = 7, subclassID = 9 }), "herb is not cloth")
    T.truthy(C.Matches("tradegoods", { classID = 7, subclassID = 9 }), "tradegoods covers herbs")
    T.truthy(C.Matches("potions", { classID = 0, subclassID = 1 }), "potion")
  end)

  T.it("only send green or better gear as boe", function()
    local _, ns = F.setup()
    local C = ns.Categories
    T.truthy(C.Matches("boe", { classID = 2, subclassID = 7, quality = 2 }), "green sword")
    T.truthy(not C.Matches("boe", { classID = 4, subclassID = 1, quality = 1 }), "white shirt")
  end)

  T.it("look up keys case-insensitively", function()
    local _, ns = F.setup()
    T.truthy(ns.Categories.Get("Cloth"), "Cloth")
    T.eq(ns.Categories.Get("nope"), nil)
  end)
end)

T.describe("Rules", function()
  T.it("send an explicit item to its alt even if another alt takes its type", function()
    local _, ns = F.setup()
    local db = ns.db
    local alpha = F.addMule(ns, "Alpha Bank")
    local zeta = F.addMule(ns, "Zeta Bank")
    ns.Mules.ToggleCategory(db, alpha, "cloth")
    ns.Mules.ToggleItem(db, zeta, F.LINEN)
    T.eq(ns.Rules.Resolve({ itemID = F.LINEN, classID = 7, subclassID = 5 }, db), zeta)
  end)

  T.it("let a specific type beat a broad one", function()
    local _, ns = F.setup()
    local db = ns.db
    local zeta = F.addMule(ns, "Zeta Bank")
    local alpha = F.addMule(ns, "Alpha Bank")
    ns.Mules.ToggleCategory(db, zeta, "cloth")
    ns.Mules.ToggleCategory(db, alpha, "tradegoods")
    local key, reason = ns.Rules.Resolve({ itemID = F.LINEN, classID = 7, subclassID = 5 }, db)
    T.eq(key, zeta, "cloth alt gets linen")
    T.eq(reason, "cloth")
    T.eq(ns.Rules.Resolve({ itemID = F.PEACEBLOOM, classID = 7, subclassID = 9 }, db), alpha, "herbs fall to tradegoods")
  end)

  T.it("give ties to the alphabetically first alt", function()
    local _, ns = F.setup()
    local db = ns.db
    local zeta = F.addMule(ns, "Zeta Bank")
    local alpha = F.addMule(ns, "Alpha Bank")
    ns.Mules.ToggleCategory(db, zeta, "cloth")
    ns.Mules.ToggleCategory(db, alpha, "cloth")
    T.eq(ns.Rules.Resolve({ itemID = F.LINEN, classID = 7, subclassID = 5 }, db), alpha)
  end)

  T.it("never send hearthstone, tools, bound, locked, quest or excluded items", function()
    local _, ns = F.setup()
    local db = ns.db
    local key = F.addMule(ns, "Vault Keeper")
    ns.Mules.ToggleCategory(db, key, "tradegoods")
    ns.Mules.ToggleItem(db, key, F.HEARTHSTONE)
    local R = ns.Rules
    T.eq(R.Resolve({ itemID = F.HEARTHSTONE, classID = 15, subclassID = 0 }, db), nil, "hearthstone")
    T.eq(R.Resolve({ itemID = F.THIEVES_TOOLS, classID = 7, subclassID = 0 }, db), nil, "thieves' tools")
    T.eq(R.Resolve({ itemID = F.LINEN, classID = 7, subclassID = 5, isBound = true }, db), nil, "bound")
    T.eq(R.Resolve({ itemID = F.LINEN, classID = 7, subclassID = 5, isLocked = true }, db), nil, "locked")
    T.eq(R.Resolve({ itemID = F.QUEST_ITEM, classID = 12, subclassID = 0 }, db), nil, "quest")
    db.exclude[F.LINEN] = true
    T.eq(R.Resolve({ itemID = F.LINEN, classID = 7, subclassID = 5 }, db), nil, "excluded")
  end)

  T.it("send a quest-type item only when it was picked for a bank alt", function()
    local _, ns = F.setup()
    local db = ns.db
    local key = F.addMule(ns, "Vault Keeper")
    ns.Mules.ToggleCategory(db, key, "tradegoods")
    ns.Mules.ToggleCategory(db, key, "reagents")
    local R = ns.Rules
    local pelt = { itemID = F.QUEST_ITEM, classID = 12, subclassID = 0, isCraftingReagent = true }
    T.eq(R.Resolve(pelt, db), nil, "no item type sends it")
    ns.Mules.ToggleItem(db, key, F.QUEST_ITEM)
    local to, reason = R.Resolve(pelt, db)
    T.eq(to, key, "picked: it goes")
    T.eq(reason, "item")
    T.eq(R.Resolve({ itemID = F.QUEST_ITEM, classID = 12, subclassID = 0, isBound = true }, db), nil,
      "a bound one stays")
    db.exclude[F.QUEST_ITEM] = true
    T.eq(R.Resolve(pelt, db), nil, "the never-send list still wins")
  end)
end)

T.describe("Mules", function()
  T.it("clean up names and find alts by name, alias or unique prefix", function()
    local _, ns = F.setup()
    local db = ns.db
    local key = F.addMule(ns, "  vault   Keeper ")
    T.eq(key, "vault keeper")
    T.eq(db.mules[key].name, "vault Keeper")
    T.eq(ns.Mules.FindExact(db, "VAULT KEEPER"), key)
    T.eq(ns.Mules.FindExact(db, "vault"), nil, "FindExact needs the full name")
    T.eq(ns.Mules.Find(db, "vault"), key, "Find accepts a unique prefix")
    T.truthy(ns.Mules.SetAlias(db, "vk", key))
    T.eq(ns.Mules.FindExact(db, "VK"), key)
  end)

  T.it("refuse ambiguous prefixes and duplicate alts", function()
    local _, ns = F.setup()
    local db = ns.db
    F.addMule(ns, "Vault Keeper")
    F.addMule(ns, "Vault Second")
    local key, err = ns.Mules.Find(db, "vault")
    T.eq(key, nil)
    T.truthy(err and err:find("more than one"), "ambiguous message")
    local again, dupErr = F.addMule(ns, "vault keeper")
    T.eq(again, nil)
    T.truthy(dupErr and dupErr:find("already"), "duplicate message")
  end)

  T.it("drop aliases with their alt", function()
    local _, ns = F.setup()
    local db = ns.db
    local key = F.addMule(ns, "Vault Keeper")
    ns.Mules.SetAlias(db, "vk", key)
    ns.Mules.Remove(db, key)
    T.eq(db.aliases.vk, nil)
  end)
end)

T.describe("Scanner", function()
  T.it("collect only this alt's mailable items, grouped by kind", function()
    local w, ns, key = F.withVault()
    ns.Mules.ToggleCategory(ns.db, key, "herb")
    w:Put(0, 1, F.PEACEBLOOM, 5)
    w:Put(0, 2, F.LINEN, 20)
    w:Put(0, 3, F.LEATHER, 10)
    w:Put(0, 4, F.LINEN, 20, { bound = true })
    w:Put(1, 1, F.LINEN, 7)
    w:Put(1, 2, F.HEARTHSTONE, 1)
    local items = ns.Scanner.Collect(ns.db, key)
    T.eq(#items, 3)
    T.eq(items[1].itemID, F.LINEN)
    T.eq(items[2].itemID, F.LINEN)
    T.eq(items[3].itemID, F.PEACEBLOOM)
    T.eq(ns.Scanner.CountAll(ns.db)[key], 3)
  end)
end)
