local T = require("harness")
local F = require("fixtures")

-- At the mailbox, what's about to be mailed looks greyed out in the game's own bags,
-- and an item's tooltip names the bank alt it goes to.

local function markShown(ns, button)
  local mark = ns.BagMarks.marks[button]
  return mark ~= nil and mark:IsShown()
end

-- The combined backpack lists bag 0's 16 slots first.
local function combinedButton(frame, bag, slot)
  return frame.buttons[bag * 16 + slot]
end

T.describe("Bag marks", function()
  T.it("grey out the stacks going to a bank alt while the mailbox is open", function()
    local w, ns = F.withVault()
    w:Put(0, 1, F.LINEN, 20)
    w:Put(0, 2, F.LINEN, 7)
    w:Put(0, 3, F.PEACEBLOOM, 5)
    local bags = w:ShowCombinedBags()
    T.truthy(not markShown(ns, combinedButton(bags, 0, 1)), "nothing before the mailbox")
    w:OpenMailbox()
    w:Flush()
    T.truthy(markShown(ns, combinedButton(bags, 0, 1)), "linen")
    T.truthy(markShown(ns, combinedButton(bags, 0, 2)), "the other linen stack")
    T.truthy(not markShown(ns, combinedButton(bags, 0, 3)), "peacebloom stays")
    T.truthy(not markShown(ns, combinedButton(bags, 0, 4)), "empty slot")
    w:CloseMailbox()
    T.truthy(not markShown(ns, combinedButton(bags, 0, 1)), "gone once the mailbox closes")
  end)

  T.it("mark a bag window opened after the mailbox, one window per bag", function()
    local w, ns = F.withVault()
    w:Put(1, 4, F.LINEN, 20)
    local window = w:ShowBagWindow(1, 1)
    window.shown = false
    w:OpenMailbox()
    w:Flush()
    window:Show()
    w:Flush()
    T.truthy(markShown(ns, window.buttons[4]), "linen in bag 1, slot 4")
    T.truthy(not markShown(ns, window.buttons[3]), "the slot next to it")
  end)

  T.it("follow the rules when they change at the mailbox", function()
    local w, ns, key = F.withVault()
    w:Put(0, 1, F.PEACEBLOOM, 5)
    local bags = w:ShowCombinedBags()
    w:OpenMailbox()
    w:Flush()
    T.truthy(not markShown(ns, combinedButton(bags, 0, 1)), "herbs stay")
    ns.Mules.ToggleCategory(ns.db, key, "herb")
    ns.UI.Refresh()
    T.truthy(markShown(ns, combinedButton(bags, 0, 1)), "herbs go now")
  end)

  T.it("unmark a stack left out of this mail", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 14, 20)
    local bags = w:ShowCombinedBags()
    w:OpenMailbox()
    w:Click(ns.UI.muleButtons[1])
    w:Flush()
    local session = ns.Mailer.session
    T.eq(#session.queue, 2, "12 attached, 2 waiting")
    local left = session.queue[1]
    local waiting = session.queue[2]
    ns.Mailer.Skip(left)
    w:Flush()
    T.truthy(not markShown(ns, combinedButton(bags, left.bag, left.slot)), "left out: not marked")
    T.truthy(markShown(ns, combinedButton(bags, waiting.bag, waiting.slot)), "still waiting: marked")
  end)
end)

T.describe("Tooltip line", function()
  T.it("names the bank alt of an item in your bags, at the mailbox or not", function()
    local w = F.withVault()
    w:Put(0, 1, F.LINEN, 20)
    w:Put(0, 2, F.PEACEBLOOM, 5)
    T.eq(w:HoverBagItem(0, 1), "Hamal: goes to Vault Keeper", "away from the mailbox")
    T.eq(w:HoverBagItem(0, 2), "", "an item that stays")
    T.eq(w:HoverBagItem(0, 3), "", "an empty slot")
    w:OpenMailbox()
    w:Flush()
    T.eq(w:HoverBagItem(0, 1), "Hamal: goes to Vault Keeper\nAlt-click: keep it this time", "at the mailbox")
    w:CloseMailbox()
    T.eq(w:HoverBagItem(0, 1), "Hamal: goes to Vault Keeper", "after it")
  end)

  T.it("says nothing at the mailbox for a stack left out of this mail", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 14, 20)
    w:OpenMailbox()
    w:Click(ns.UI.muleButtons[1])
    w:Flush()
    local left = ns.Mailer.session.queue[1]
    ns.Mailer.Skip(left)
    w:Flush()
    T.eq(w:HoverBagItem(left.bag, left.slot), "")
  end)

  T.it("stays out of the bank, Hamal's own icons, and tooltips you switched it off for", function()
    local w, ns = F.withVault()
    w:Put(-1, 1, F.LINEN, 20)
    w:Put(0, 1, F.LINEN, 20)
    T.eq(w:HoverBagItem(-1, 1), "", "bank slot")
    ns.Widgets.ShowItemTooltip(ns.UI.panel or UIParent, { bag = 0, slot = 1, itemID = F.LINEN })
    T.truthy(not table.concat(GameTooltip.lines, "\n"):find("Hamal: goes to"), "Hamal's own icon")
    SlashCmdList.HAMAL("")
    ns.Config.ShowTab("options")
    local check = ns.Config.widgets.tooltipCheck
    T.truthy(check:GetChecked(), "on by default")
    check:Click()
    T.eq(ns.db.options.bagTooltips, false)
    T.eq(w:HoverBagItem(0, 1), "", "switched off")
  end)

  T.it("reads only the hovered slot away from the mailbox, and nothing when switched off", function()
    local w, ns = F.withVault()
    w:Fill(F.LINEN, 30, 20)
    w.calls.info = 0
    w:HoverBagItem(0, 1)
    T.eq(w.calls.info, 1, "one slot")
    ns.db.options.bagTooltips = false
    w.calls.info = 0
    w:HoverBagItem(0, 1)
    T.eq(w.calls.info, 0, "switched off")
  end)
end)

local GOES = "Hamal: goes to Vault Keeper\nAlt-click: keep it this time"
local STAYS = "Hamal: stays in your bags this time\nAlt-click: send it"

T.describe("Alt-click in the bags", function()
  T.it("keeps an item in the bags this visit, and a second Alt-click sends it again", function()
    local w, ns = F.withVault()
    w:Put(0, 1, F.LINEN, 20)
    w:Put(0, 2, F.LINEN, 7)
    local bags = w:ShowCombinedBags()
    w:OpenMailbox()
    w:Flush()
    T.eq(w:AltClickBagItem(0, 1), STAYS, "the tooltip says so at once")
    T.truthy(w:Printed("stays in your bags this time"), "one chat line")
    T.truthy(not markShown(ns, combinedButton(bags, 0, 1)), "not grey any more")
    T.truthy(not markShown(ns, combinedButton(bags, 0, 2)), "nor the other stack of it")
    T.eq(w:HoverBagItem(0, 2), STAYS, "every stack of it stays")
    T.eq(ns.UI.muleButtons[1]:GetText(), "Vault Keeper (0)")
    T.eq(ns.Mailer.SendAll(true), false, "nothing to send")
    T.eq(#w.sent, 0)

    T.eq(w:AltClickBagItem(0, 2), GOES)
    T.truthy(markShown(ns, combinedButton(bags, 0, 1)), "grey again")
    T.eq(ns.UI.muleButtons[1]:GetText(), "Vault Keeper (2)")
    w:Click(ns.UI.sendAllButton)
    w:Flush()
    T.eq(w:StacksInBags(F.LINEN), 0, "sent after all")
  end)

  T.it("takes the item out of a mail being filled, and puts it back", function()
    local w, ns, key = F.withVault()
    ns.Mules.ToggleCategory(ns.db, key, "leather")
    w:Fill(F.LINEN, 3, 20)
    w:Put(1, 1, F.LEATHER, 10)
    w:Put(1, 2, F.LEATHER, 10)
    ns.db.options.stackFirst = false
    w:OpenMailbox()
    w:Click(ns.UI.muleButtons[1])
    T.eq(ns.Mailer.AttachedCount(), 5)
    w:AltClickBagItem(1, 1)
    T.eq(ns.Mailer.AttachedCount(), 3, "both leather stacks out of the form")
    T.eq(w:LockedInBags(), 3, "and unlocked in the bags")
    w:AltClickBagItem(1, 1)
    T.eq(ns.Mailer.AttachedCount(), 5, "back in")
    w:AltClickBagItem(1, 2)
    w:Click(ns.UI.sendButton)
    w:Flush()
    T.eq(w:StacksInBags(F.LINEN), 0, "the linen went")
    T.eq(w:StacksInBags(F.LEATHER), 2, "the leather stayed")
    T.eq(ns.Mailer.session, nil)
  end)

  T.it("ends a bank alt's mail when nothing is left for it, and Send all goes on", function()
    local w, ns, vault = F.withVault()
    local herbs = F.addMule(ns, "Herb Bank")
    ns.Mules.ToggleCategory(ns.db, herbs, "herb")
    w:Put(0, 1, F.LINEN, 20)
    w:Put(0, 2, F.PEACEBLOOM, 5)
    w:OpenMailbox()
    w:Click(ns.UI.muleButtons[2])
    T.eq(ns.Mailer.session.key, vault)
    w:AltClickBagItem(0, 1)
    T.eq(ns.Mailer.session, nil, "nothing left for Vault Keeper")
    T.eq(next(w.mail), nil, "nothing left in the form")
    T.eq(w:LockedInBags(), 0)
    w:Click(ns.UI.sendAllButton)
    w:Flush()
    T.eq(#w.sent, 1)
    T.eq(w.sent[1].to, "Herb Bank")
    T.eq(w:StacksInBags(F.LINEN), 1, "the linen stayed")
  end)

  T.it("forgets what it kept once the mailbox closes", function()
    local w, ns = F.withVault()
    w:Put(0, 1, F.LINEN, 20)
    local bags = w:ShowCombinedBags()
    w:OpenMailbox()
    w:Flush()
    w:AltClickBagItem(0, 1)
    w:CloseMailbox()
    T.eq(w:HoverBagItem(0, 1), "Hamal: goes to Vault Keeper", "away from the mailbox")
    w:OpenMailbox()
    w:Flush()
    T.truthy(markShown(ns, combinedButton(bags, 0, 1)), "grey again at the next visit")
  end)

  T.it("leaves every other click alone", function()
    local w, ns = F.withVault()
    w:Put(0, 1, F.LINEN, 20)
    w:Put(0, 2, F.PEACEBLOOM, 5)
    w:AltClickBagItem(0, 1)
    T.eq(next(ns.Rules.held), nil, "away from the mailbox")
    w:OpenMailbox()
    w:Flush()
    w:AltClickBagItem(0, 1, "RightButton")
    T.eq(next(ns.Rules.held), nil, "right button")
    w.shift = true
    w:AltClickBagItem(0, 1)
    w.shift = false
    T.eq(next(ns.Rules.held), nil, "Alt and Shift")
    w:AltClickLink(F.LINEN)
    T.eq(next(ns.Rules.held), nil, "a chat link")
    w.printed = {}
    w:AltClickBagItem(0, 2)
    T.eq(next(ns.Rules.held), nil, "an item that stays anyway")
    T.eq(#w.printed, 0, "and no chat line for it")
    w:Put(-1, 1, F.LINEN, 20)
    w:AltClickBagItem(-1, 1)
    T.eq(next(ns.Rules.held), nil, "the bank")
  end)

  T.it("says Option-click on a Mac, where Option is the game's Alt key", function()
    local w, ns = F.withVault()
    w.mac = true
    w:Put(0, 1, F.LINEN, 20)
    w:OpenMailbox()
    w:Flush()
    T.eq(w:HoverBagItem(0, 1), "Hamal: goes to Vault Keeper\nOption-click: keep it this time")
    T.eq(w:AltClickBagItem(0, 1), "Hamal: stays in your bags this time\nOption-click: send it")
    T.truthy(w:Printed("Option%-click it again to send it"), "the chat line too")
    SlashCmdList.HAMAL("")
    ns.Config.ShowTab("options")
    T.truthy(ns.Config.widgets.altClickCheck.label:GetText():find("Option%-click an item"), "and Options")
  end)

  T.it("can be switched off in Options", function()
    local w, ns = F.withVault()
    w:Put(0, 1, F.LINEN, 20)
    SlashCmdList.HAMAL("")
    ns.Config.ShowTab("options")
    local check = ns.Config.widgets.altClickCheck
    T.truthy(check:GetChecked(), "on by default")
    check:Click()
    T.eq(ns.db.options.altClickKeep, false)
    w:OpenMailbox()
    w:Flush()
    T.eq(w:AltClickBagItem(0, 1), "Hamal: goes to Vault Keeper", "no hint, nothing kept")
    T.eq(next(ns.Rules.held), nil)
  end)
end)
